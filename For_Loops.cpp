#include <iostream>
using namespace std;

int main(){

    // FOR LOOPS
    cout<<"For Loop In C++"<<endl;
    int i,j;
    cout<<"Enter Starting Number: "<<endl;
    cin>>i;
    cout<<"Enter Ending Number: "<<endl;
    cin>>j;
    for (i; i<=j; i++){
        cout<<"Num "<<i<<endl;
    }

    return 0;
}
